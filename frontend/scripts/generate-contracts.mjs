// Offline generation from the backend's reviewed public export. No remote refs.
import { readFile, writeFile, mkdir } from "node:fs/promises";
import openapiTS, { astToString } from "openapi-typescript";
import Ajv2020 from "ajv/dist/2020.js";
import addFormats from "ajv-formats";
import standaloneCode from "ajv/dist/standalone/index.js";

const check = process.argv.slice(2).join(" ") === "--check";
if (process.argv.length > 2 && !check) throw new Error("Unknown generation option.");
const source = JSON.parse(await readFile(new URL("../../contracts/openapi.json", import.meta.url), "utf8"));
function localReferences(value) {
  if (!value || typeof value !== "object") return;
  for (const [key, child] of Object.entries(value)) {
    if (key === "$ref" && (typeof child !== "string" || !child.startsWith("#/components/schemas/"))) {
      throw new Error("Only local public-schema references are allowed.");
    }
    localReferences(child);
  }
}
localReferences(source);
const output = new URL("../src/lib/generated/", import.meta.url);
const schema = JSON.parse(JSON.stringify(source.components.schemas).replaceAll(
  "#/components/schemas/", "#/$defs/",
));
const ajv = new Ajv2020({
  strict: true, allErrors: false, ownProperties: true,
  coerceTypes: false, useDefaults: false, removeAdditional: false,
  code: { source: true, optimize: true },
});
addFormats(ajv);
ajv.addSchema({ $id: "urn:goodshowroom:public:v1", $defs: schema });
const names = ["CreateChatRequest", "TurnRequest", "ChatResultEnvelope", "ErrorEnvelope"];
const exports = Object.fromEntries(names.map((name) => [name, `urn:goodshowroom:public:v1#/$defs/${name}`]));
const files = {
  "api-types.ts": "// Generated by scripts/generate-contracts.mjs. Do not edit.\n"
    + astToString(await openapiTS(source, { silent: true })),
  "validators.cjs": "// Generated by scripts/generate-contracts.mjs. Do not edit.\n"
    + standaloneCode(ajv, exports) + "\n",
  "validators.d.cts": "// Generated by scripts/generate-contracts.mjs. Do not edit.\n"
    + names.map((name) => `export function ${name}(value: unknown): boolean;`).join("\n") + "\n",
  "contract-meta.json": JSON.stringify({
    limits: source["x-contract-limits"], errors: source["x-error-catalog"],
  }, null, 2) + "\n",
};
if (!check) await mkdir(output, { recursive: true });
for (const [name, content] of Object.entries(files)) {
  const path = new URL(name, output);
  if (check) {
    if (await readFile(path, "utf8").catch(() => null) !== content) {
      throw new Error("Generated frontend contracts are stale. Regenerate contracts.");
    }
  } else await writeFile(path, content, "utf8");
}
console.log(check ? "Frontend contracts match the public export." : "Frontend contracts generated.");
